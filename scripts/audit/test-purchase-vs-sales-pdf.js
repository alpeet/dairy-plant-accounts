/**
 * Purchase vs Sales — print / PDF verification (Electron runtime)
 * ==============================================================
 * Runs the SAME document and the SAME printToPDF options the app's
 * `print:pdf` handler uses (renderer/css/print.css, A4, DisplayHeaderFooter
 * with a "Page X of Y" footer) and then inspects the produced PDF:
 *
 *   · it is a real PDF file (header + %%EOF), not a renamed HTML file
 *   · it has more than one page (a BS month is a multi-page document)
 *   · page size is A4 portrait
 *   · the document carries print.css, whose `thead { display: table-header-group }`
 *     repeats every table header on each printed page
 *
 * The report document is generated by plain node (better-sqlite3 is built for
 * node here); Electron only renders it. That keeps the check independent of
 * the node/Electron native-module ABI.
 *
 * Run (cannot run under plain node — needs Electron's app.whenReady):
 *   npx electron scripts/audit/test-purchase-vs-sales-pdf.js
 */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');
const { app, BrowserWindow } = require('electron');

if (typeof app === 'undefined' || !app) {
    console.error('This check needs the Electron runtime: npx electron scripts/audit/test-purchase-vs-sales-pdf.js');
    process.exit(2);
}

const ROOT = path.resolve(__dirname, '..', '..');
const DB_PATH = process.env.PVS_DB || path.join(os.tmpdir(), 'pvs-report-live-copy.db');
const OUT_DIR = path.join(os.tmpdir(), 'pvs-pdf-check');
const HTML_PATH = path.join(OUT_DIR, 'report.html');
const META_PATH = path.join(OUT_DIR, 'meta.json');

let passed = 0;
let failed = 0;
function check(name, condition, detail) {
    if (condition) { passed++; console.log(`  ✅ ${name}`); }
    else { failed++; console.log(`  ❌ ${name}${detail !== undefined ? ` — ${JSON.stringify(detail)}` : ''}`); }
}

/** Count PDF pages from the page tree (/Count) — no external tools needed. */
function pdfPageCount(buffer) {
    const text = buffer.toString('latin1');
    const counts = [...text.matchAll(/\/Type\s*\/Pages[\s\S]{0,300}?\/Count\s+(\d+)/g)].map(m => Number(m[1]));
    if (counts.length) return Math.max(...counts);
    const pages = text.match(/\/Type\s*\/Page[^s]/g);
    return pages ? pages.length : 0;
}

/** Generate the print document with plain node (node ABI, real database). */
function buildDocument() {
    const script = `
        const fs = require('fs');
        const Database = require('better-sqlite3');
        const bs = require('./shared/bs-calendar');
        const { buildPurchaseVsSalesHTML } = require('./shared/report-purchase-vs-sales');
        const db = new Database(process.argv[1], { readonly: true });
        const range = bs.bsMonthRange(process.argv[4] || '2083-07');
        const doc = buildPurchaseVsSalesHTML(db, { from_date: range.from_date, to_date: range.to_date });
        const css = fs.readFileSync('renderer/css/print.css', 'utf8');
        const html = '<!DOCTYPE html><html><head><meta charset="utf-8"><title>' + doc.title +
            '</title><style>' + css + '</style></head><body>' + doc.html + '</body></html>';
        fs.mkdirSync(process.argv[3], { recursive: true });
        fs.writeFileSync(process.argv[2], html, 'utf8');
        fs.writeFileSync(process.argv[3] + '/meta.json', JSON.stringify({
            filename: doc.filename,
            title: doc.title,
            htmlLength: html.length,
            period: jobPeriod(range)
        }));
        function jobPeriod(r) { return r.from_date + ' to ' + r.to_date; }
    `;
    const res = spawnSync('node', ['-e', script, DB_PATH, HTML_PATH, OUT_DIR], {
        cwd: ROOT,
        encoding: 'utf8'
    });
    if (res.status !== 0) {
        throw new Error('Could not build the report document: ' + ((res.stderr || res.stdout || '').trim()));
    }
    return JSON.parse(fs.readFileSync(META_PATH, 'utf8'));
}

app.whenReady().then(async () => {
    try {
        if (!fs.existsSync(DB_PATH)) {
            console.error(`Database not found: ${DB_PATH}`);
            console.error('Create it first (a /tmp copy, never the live file).');
            app.exit(2);
            return;
        }

        const meta = buildDocument();
        console.log(`\n   document: ${meta.filename} (${meta.htmlLength} bytes of HTML, ${meta.period})`);
        const html = fs.readFileSync(HTML_PATH, 'utf8');

        check('print document built from the report engine', meta.htmlLength > 100000, meta.htmlLength);
        check('print document carries print.css', html.includes('table-header-group'));
        check('every table header repeats on each printed page', /thead\s*\{\s*display:\s*table-header-group/.test(html));
        check('document has one <thead> per report table', (html.match(/<thead>/g) || []).length === 5,
            (html.match(/<thead>/g) || []).length);

        const win = new BrowserWindow({ width: 900, height: 1200, show: false });
        await win.loadFile(HTML_PATH);

        const footerText = String(meta.title).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
        const pdf = await win.webContents.printToPDF({
            printBackground: true,
            landscape: false,
            pageSize: 'A4',
            margins: { top: 0.4, bottom: 0.4, left: 0.4, right: 0.4 },
            displayHeaderFooter: true,
            headerTemplate: '<span></span>',
            footerTemplate: '<div style="width:100%;padding:0 10mm;font-size:7pt;color:#777;font-family:Arial,Helvetica,sans-serif;">'
                + '<span>' + footerText + '</span>'
                + '<span style="float:right;">Page <span class="pageNumber"></span> of <span class="totalPages"></span></span>'
                + '</div>'
        });

        const pdfPath = path.join(OUT_DIR, meta.filename);
        fs.writeFileSync(pdfPath, pdf);

        const size = fs.statSync(pdfPath).size;
        const pages = pdfPageCount(pdf);
        const header = pdf.slice(0, 5).toString('latin1');
        const mediaBox = pdf.toString('latin1').match(/\/MediaBox\s*\[\s*0\s+0\s+([\d.]+)\s+([\d.]+)\s*\]/);

        check('PDF file written with the report filename', fs.existsSync(pdfPath) && /\.pdf$/.test(pdfPath), pdfPath);
        check('PDF has a real %PDF header (not renamed HTML)', header === '%PDF-', header);
        check('PDF is substantial (over 100 KB)', size > 100 * 1024, size);
        check('PDF has more than one page', pages > 1, pages);
        check('page media box is A4 portrait (595 × 842 pt)', !!mediaBox
            && Math.abs(Number(mediaBox[1]) - 595) < 3 && Math.abs(Number(mediaBox[2]) - 842) < 3,
            mediaBox && mediaBox.slice(1));
        check('PDF ends with %%EOF (complete file)', pdf.toString('latin1').trimEnd().endsWith('%%EOF'));

        console.log(`\n   PDF: ${pdfPath}`);
        console.log(`   pages: ${pages}, size: ${(size / 1024).toFixed(1)} KB`);

        win.destroy();
    } catch (err) {
        failed++;
        console.error('PDF verification failed:', err && err.stack ? err.stack : err);
    }

    console.log(`\n═══════════════════════════════════════════`);
    console.log(`  Purchase-vs-Sales PDF: ${passed} passed, ${failed} failed`);
    console.log(`═══════════════════════════════════════════\n`);
    app.exit(failed > 0 ? 1 : 0);
});
